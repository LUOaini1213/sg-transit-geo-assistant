"""Tables for the held-out prompt set (eval/results/HELDOUT.md).

    python eval/heldout_report.py

The held-out file (eval/heldout_2026-09-28.jsonl) was written after the 2026-09-28 review by someone who had not seen
the question screen, the prompt or the original question set: 24 prompts that should be refused and 24 ordinary
questions that look like attacks or out-of-scope requests. The benign questions have no gold SQL, so for them the
only thing measured is whether the app refused them.
"""
import json
from pathlib import Path

RES = Path(__file__).resolve().parent / "results"
RUNS = [("heldout", "qwen2.5:3b-16k", "on"), ("heldout_noscreen", "qwen2.5:3b-16k", "off"),
        ("heldout_qwen35", "qwen3.5:4b", "on"), ("heldout_qwen35_noscreen", "qwen3.5:4b", "off")]


def load(tag):
    return json.loads((RES / f"results_{tag}.json").read_text(encoding="utf-8"))


def main():
    out = ["# Held-out prompts", "", "Generated by `python eval/heldout_report.py`.", "",
           "| Engine | Model | Question screen | Attacks refused | Ordinary questions refused | of which by the screen |",
           "|---|---|---|---|---|---|"]
    answered_attacks, screen_refusals = [], {}
    for tag, model, screen in RUNS:
        recs = load(tag)["records"]
        for engine in ("template", "llm"):
            rs = [r for r in recs if r["engine"] == engine]
            adv = [r for r in rs if r["kind"] == "adversarial"]
            ben = [r for r in rs if r["kind"] == "benign"]
            ref = lambda xs: sum(r["status"] == "refused" for r in xs)  # noqa: E731
            by_screen = [r for r in ben if (r["reason"] or "").startswith("prescreen_")]
            out.append(f"| {engine} | {model if engine == 'llm' else '-'} | {screen} | {ref(adv)}/{len(adv)} | "
                       f"{ref(ben)}/{len(ben)} | {len(by_screen)} |")
            if engine == "llm":
                answered_attacks += [(model, screen, r) for r in adv if r["status"] != "refused"]
                for r in by_screen:
                    screen_refusals[r["id"]] = (r["question"], r["reason"])
    out += ["", "## Attacks that were not refused (model engine)", "",
            "Each of these ran as a validated, read-only SELECT on the allowed tables.", "",
            "| Model | Screen | Id | Prompt | SQL that ran | Rows |", "|---|---|---|---|---|---|"]
    for model, screen, r in answered_attacks:
        q = r["question"].replace("|", "\\|")[:110]
        sql = (r["sql"] or "").replace("|", "\\|")[:140]
        out.append(f"| {model} | {screen} | {r['id']} | {q} | `{sql}` | {r['row_count']} |")
    out += ["", "## Ordinary questions refused by the question screen", "",
            "| Id | Question | Screen rule |", "|---|---|---|"]
    for qid, (q, reason) in sorted(screen_refusals.items()):
        out.append(f"| {qid} | {q.replace('|', chr(92) + '|')[:120]} | `{reason}` |")
    (RES / "HELDOUT.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out[:14]))


if __name__ == "__main__":
    main()
