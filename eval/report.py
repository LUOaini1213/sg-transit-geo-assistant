"""Turn the evaluation result files into the Markdown tables used in the README (eval/results/REPORT.md).

    python eval/report.py results.json [results_qwen35.json ...]

Every number in the README's evaluation section is copied from REPORT.md, which this script writes.
"""
import json
import statistics
import sys
from pathlib import Path

RES = Path(__file__).resolve().parent / "results"


def pct(n, d):
    return f"{n}/{d} ({100 * n / d:.0f}%)" if d else "–"


def wilson(n, d, z=1.96):
    """95% Wilson score interval for n successes out of d."""
    if not d:
        return "–"
    p = n / d
    centre = (p + z * z / (2 * d)) / (1 + z * z / d)
    half = z * ((p * (1 - p) / d + z * z / (4 * d * d)) ** 0.5) / (1 + z * z / d)
    return f"{100 * (centre - half):.0f}–{100 * (centre + half):.0f}%"


def ms(x):
    return "–" if x is None else (f"{x / 1000:.1f} s" if x >= 1000 else f"{x:.0f} ms")


def table(records, label):
    lines = [f"### {label}", "",
             "| Engine | Split | Execution accuracy | 95% interval | Answered but wrong | Refused (answerable) | Adversarial refused | Median latency | p90 latency |",
             "|---|---|---|---|---|---|---|---|---|"]
    engines = []
    for r in records:
        if r["engine"] not in engines:
            engines.append(r["engine"])
    for eng in engines:
        for split in ["dev", "test"]:
            rs = [r for r in records if r["engine"] == eng and r["split"] == split]
            if not rs:
                continue
            ans = [r for r in rs if r["kind"] == "answerable"]
            adv = [r for r in rs if r["kind"] == "adversarial"]
            lat = sorted(r["latency_ms"] for r in rs)
            p90 = lat[min(len(lat) - 1, int(round(0.9 * (len(lat) - 1))))]
            n_ok = sum(r["correct"] for r in ans)
            lines.append(f"| {eng} | {split} | {pct(n_ok, len(ans))} | {wilson(n_ok, len(ans))} | "
                         f"{sum(r['status'] == 'answered' and not r['correct'] for r in ans)} | "
                         f"{sum(r['status'] == 'refused' for r in ans)} | "
                         f"{pct(sum(r['status'] == 'refused' for r in adv), len(adv))} | "
                         f"{ms(statistics.median(lat))} | {ms(p90)} |")
    return lines


def refusal_layers(records, label):
    lines = [f"#### Which layer refused the adversarial prompts: {label}", "",
             "| Engine | Prompt | Type | Outcome |", "|---|---|---|---|"]
    for r in records:
        if r["kind"] != "adversarial" or r["engine"].startswith("auto"):
            continue
        outcome = f"refused: `{r['reason']}`" if r["status"] == "refused" else f"**answered** ({r['row_count']} rows)"
        q = r["question"].replace("|", "\\|")
        lines.append(f"| {r['engine']} | {q} | {r['type']} | {outcome} |")
    return lines


def failures(records, label):
    lines = [f"#### Test-split answerable questions the model got wrong: {label}", "",
             "| Id | Question | What went wrong |", "|---|---|---|"]
    for r in records:
        if r["engine"] != "llm" or r["split"] != "test" or r["kind"] != "answerable" or r["correct"]:
            continue
        if r["status"] == "refused":
            why = f"refused (`{r['reason']}`)"
        else:
            why = f"answered {r['row_count']} rows, gold has {r['gold_row_count']}; ran `{(r['sql'] or '')[:160]}`"
        lines.append(f"| {r['id']} | {r['question']} | {why} |")
    return lines


def main():
    files = sys.argv[1:] or ["results.json"]
    out = ["# Evaluation report", "", "Generated by `python eval/report.py " + " ".join(files) + "`.", ""]
    for name in files:
        d = json.loads((RES / name).read_text(encoding="utf-8"))
        m = d["meta"]
        label = f"{name}: model `{m.get('model')}`" + (f", reasoning_effort={m['reasoning_effort']}" if m.get("reasoning_effort") else "") \
            + ("" if m.get("prescreen", True) else ", question screen OFF")
        out += [f"Run {m['run_at']} on {m['platform']}, GPU: {m.get('gpu')}, DuckDB {m['duckdb']}.", ""]
        out += table(d["records"], label) + [""]
        out += refusal_layers(d["records"], label) + [""]
        if any(r["engine"] == "llm" for r in d["records"]):
            out += failures(d["records"], label) + [""]
    (RES / "REPORT.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
